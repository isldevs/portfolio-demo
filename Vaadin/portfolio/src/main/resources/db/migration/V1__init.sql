CREATE TABLE portfolio_profile (
  id BIGINT PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  headline VARCHAR(220) NOT NULL,
  location VARCHAR(120) NOT NULL DEFAULT '',
  email VARCHAR(254) NOT NULL,
  introduction VARCHAR(1400) NOT NULL DEFAULT '',
  about_text TEXT NOT NULL DEFAULT '',
  github_url VARCHAR(500) NOT NULL DEFAULT '',
  linkedin_url VARCHAR(500) NOT NULL DEFAULT '',
  cv_url VARCHAR(500) NOT NULL DEFAULT '',
  availability VARCHAR(180) NOT NULL DEFAULT ''
);
CREATE TABLE portfolio_project (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(100) NOT NULL UNIQUE,
  title VARCHAR(150) NOT NULL,
  summary VARCHAR(500) NOT NULL,
  details TEXT NOT NULL DEFAULT '',
  technology VARCHAR(400) NOT NULL DEFAULT '',
  source_url VARCHAR(500) NOT NULL DEFAULT '',
  demo_url VARCHAR(500) NOT NULL DEFAULT '',
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE portfolio_skill (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  category VARCHAR(100) NOT NULL,
  proficiency INTEGER NOT NULL DEFAULT 75 CHECK (proficiency BETWEEN 0 AND 100),
  sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE portfolio_experience (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_title VARCHAR(160) NOT NULL,
  organization VARCHAR(160) NOT NULL,
  period VARCHAR(120) NOT NULL,
  location VARCHAR(160) NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE contact_message (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_name VARCHAR(120) NOT NULL,
  sender_email VARCHAR(254) NOT NULL,
  subject VARCHAR(160) NOT NULL,
  message TEXT NOT NULL,
  received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  is_read BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_contact_message_received ON contact_message(received_at DESC);
CREATE TABLE admin_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL
);
